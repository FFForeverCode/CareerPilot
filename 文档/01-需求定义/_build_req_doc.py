def post_process(path):
    tmp = path + ".tmp"
    with zipfile.ZipFile(path, "r") as zin, zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        names = zin.namelist()
        for item in names:
            data = zin.read(item)
            if item == "word/header1.xml":
                text = data.decode("utf-8")
                text = text.replace("运动健康与健身房管理系统", "大学生职业生涯规划系统")
                data = text.encode("utf-8")
            elif item == "word/settings.xml":
                text = data.decode("utf-8")
                if "w:trackRevisions" not in text:
                    start = text.find("<w:settings")
                    idx = text.find(">", start)
                    text = text[: idx + 1] + "<w:trackRevisions/><w:updateFields w:val=\"true\"/>" + text[idx + 1 :]
                data = text.encode("utf-8")
            elif item == "word/_rels/document.xml.rels":
                text = data.decode("utf-8")
                if "comments.xml" not in text:
                    text = text.replace(
                        "</Relationships>",
                        '<Relationship Id="rId20" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/comments" Target="comments.xml"/></Relationships>',
                    )
                data = text.encode("utf-8")
            elif item == "[Content_Types].xml":
                text = data.decode("utf-8")
                if "/word/comments.xml" not in text:
                    text = text.replace(
                        "</Types>",
                        '<Override PartName="/word/comments.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.comments+xml"/></Types>',
                    )
                data = text.encode("utf-8")
            zout.writestr(item, data)
        zout.writestr("word/comments.xml", comments_xml().encode("utf-8"))
    shutil.move(tmp, path)


def comments_xml():
    initials = {"陈晓飞": "陈", "高研": "高", "陈清驰": "清", "辛译维": "辛", "范雨涵": "范"}
    parts = [
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>',
        f'<w:comments xmlns:w="{W_NS}">',
    ]
    for c in COMMENTS:
        ini = initials.get(c["author"], "评")
        text = (c["text"].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))
        parts.append(
            f'<w:comment w:id="{c["id"]}" w:author="{c["author"]}" w:date="{c["date"]}" w:initials="{ini}">'
            f"<w:p><w:r><w:t>{text}</w:t></w:r></w:p></w:comment>"
        )
    parts.append("</w:comments>")
    return "".join(parts)


