def add_toc(doc):
    lines = [
        "1  引言",
        "2  项目概述",
        "3  功能需求",
        "4  数据需求",
        "5  界面与交互需求",
        "6  非功能需求",
        "7  实施计划与里程碑",
        "8  验收标准",
        "9  风险分析与应对",
        "附录A  需求追踪矩阵",
        "附录B  需求变更记录",
        "附录C  术语一致性说明",
    ]
    p = doc.add_paragraph(style="BodyFlat")
    r1 = OxmlElement("w:r")
    fc1 = OxmlElement("w:fldChar")
    fc1.set(qn("w:fldCharType"), "begin")
    r1.append(fc1)
    p._p.append(r1)
    r2 = OxmlElement("w:r")
    instr = OxmlElement("w:instrText")
    instr.set(XML_SPACE, "preserve")
    instr.text = ' TOC \\o "1-3" \\h \\z \\u '
    r2.append(instr)
    p._p.append(r2)
    r3 = OxmlElement("w:r")
    fc2 = OxmlElement("w:fldChar")
    fc2.set(qn("w:fldCharType"), "separate")
    r3.append(fc2)
    p._p.append(r3)
    for i, line in enumerate(lines):
        p._p.append(_run(line))
        if i != len(lines) - 1:
            br = OxmlElement("w:r")
            br.append(OxmlElement("w:br"))
            p._p.append(br)
    r4 = OxmlElement("w:r")
    fc3 = OxmlElement("w:fldChar")
    fc3.set(qn("w:fldCharType"), "end")
    r4.append(fc3)
    p._p.append(r4)


