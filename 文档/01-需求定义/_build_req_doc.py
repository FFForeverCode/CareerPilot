def _rpr():
    rpr = OxmlElement("w:rPr")
    lang = OxmlElement("w:lang")
    lang.set(qn("w:eastAsia"), "zh-CN")
    rpr.append(lang)
    return rpr


def _text_el(tag, text):
    el = OxmlElement(tag)
    if text[:1].isspace() or (text and text[-1:].isspace()):
        el.set(XML_SPACE, "preserve")
    el.text = text
    return el


def _run(text):
    r = OxmlElement("w:r")
    r.append(_rpr())
    r.append(_text_el("w:t", text))
    return r


def _del_run(text):
    r = OxmlElement("w:r")
    r.append(_rpr())
    r.append(_text_el("w:delText", text))
    return r


def _rev(tag, author, date):
    global REV_N
    el = OxmlElement(tag)
    el.set(qn("w:id"), str(REV_N))
    REV_N += 1
    el.set(qn("w:author"), author)
    el.set(qn("w:date"), date)
    return el


def add_rich(doc, style, parts):
    p = doc.add_paragraph(style=style)
    if isinstance(parts, str):
        parts = [parts]
    for piece in parts:
        if isinstance(piece, str):
            if piece:
                p._p.append(_run(piece))
            continue
        kind = piece[0]
        if kind == "del":
            _, text, author, date = piece
            el = _rev("w:del", author, date)
            el.append(_del_run(text))
            p._p.append(el)
        elif kind == "ins":
            _, text, author, date = piece
            el = _rev("w:ins", author, date)
            el.append(_run(text))
            p._p.append(el)
        elif kind == "cmt":
            _, text, comment, author, date = piece
            cid = str(len(COMMENTS))
            COMMENTS.append({"id": cid, "author": author, "date": date, "text": comment})
            start = OxmlElement("w:commentRangeStart")
            start.set(qn("w:id"), cid)
            p._p.append(start)
            p._p.append(_run(text))
            end = OxmlElement("w:commentRangeEnd")
            end.set(qn("w:id"), cid)
            p._p.append(end)
            r = OxmlElement("w:r")
            r.append(_rpr())
            ref = OxmlElement("w:commentReference")
            ref.set(qn("w:id"), cid)
            r.append(ref)
            p._p.append(r)
        else:
            raise ValueError(kind)
    return p


